// Wooden inn sign, thimble bell and the changes a guest can see on returning.
type Art = [number, number, (g: CanvasRenderingContext2D) => void];
const palette: Record<string, string> = {
  d: '#363044',
  w: '#805850',
  t: '#b78264',
  h: '#e9bb7e',
  g: '#e8ab49',
  y: '#ffe199',
  b: '#59839c',
  c: '#a1d6ce',
  v: '#9679a4',
  p: '#e1b8bf',
  r: '#b35d60',
  s: '#eae0d0',
};
function tiles(rows: string[]): Art {
  return [
    16,
    20,
    (g) =>
      rows.forEach((row, y) =>
        [...row].forEach((pixel, x) => {
          if (pixel === '.') return;
          g.fillStyle = palette[pixel];
          g.fillRect(x, y + 2, 1, 1);
        }),
      ),
  ];
}
