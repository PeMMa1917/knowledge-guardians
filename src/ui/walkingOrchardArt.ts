type Drawing = [number, number, (g: CanvasRenderingContext2D) => void];
const c: Record<string, string> = {
  i: '#293240',
  d: '#436756',
  v: '#649264',
  l: '#b1c77a',
  h: '#eed6a2',
  c: '#af735d',
  r: '#a05166',
  p: '#e7928c',
  t: '#7cb9ae',
  w: '#75575b',
};
function image(lines: string[]): Drawing {
  return [
    Math.max(...lines.map((l) => l.length)),
    lines.length,
    (g) =>
      lines.forEach((row, y) =>
        Array.from(row).forEach((key, x) => {
          if (c[key]) {
            g.fillStyle = c[key];
            g.fillRect(x, y, 1, 1);
          }
        }),
      ),
  ];
}
